'use server'

import { revalidatePath } from 'next/cache'
import { createClient } from '@/lib/supabase/server'

export interface AddChildResponse {
    success: boolean;
    data?: any;
    error?: string;
}

export async function addChildFromScan(childId: string): Promise<AddChildResponse> {
    const supabase = await createClient()

    const trimmedChildId = childId?.trim()

    if (!trimmedChildId) {
        return { success: false, error: 'Child ID is required' }
    }

    // 1. Fetch child name from 'Children' table with the matching ID
    const { data: child, error: childError } = await supabase
        .from('Children')
        .select('name')
        .eq('id', trimmedChildId)
        .single();

    if (childError || !child) {
        console.error('Child not found in Children table:', childError);
        return {
            success: false,
            error: childError?.message || 'Child not found with the scanned ID',
        };
    }

    // 2. Insert into 'Parents' table
    // 'id' and 'created_at' are auto-generated by Supabase
    const { data, error } = await supabase
        .from('Parents')
        .insert({
            Child: trimmedChildId,
            child_name: child.name,
        })
        .select()
        .single();

    if (error) {
        console.error('Failed to insert into Parents table:', error);
        return { success: false, error: error.message || 'Could not link child' };
    }

    revalidatePath('/[locale]/parent')
    revalidatePath('/[locale]/parent/addChild')

    return {
        success: true,
        data,
    };
}
